-- Bank Customer Churn Analysis
-- Database: BANK_DB

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID INT PRIMARY KEY,
    NAME VARCHAR(100),
    AGE INT,
    CREDIT_SCORE INT,
    BALANCE FLOAT,
    NUM_OF_PRODUCTS INT,
    IS_ACTIVE BOOLEAN,
    TENURE_YEARS INT,
    EXITED BOOLEAN
);

