-- Bank Customer Churn Analysis Queries

-- 1. Total Customers & Overall Churn Rate
SELECT 
  COUNT(*) AS TOTAL_CUSTOMERS,
  SUM(CASE WHEN EXITED = TRUE THEN 1 ELSE 0 END) AS CHURNED_CUSTOMERS,
  ROUND(CHURNED_CUSTOMERS * 100.0 / TOTAL_CUSTOMERS, 2) AS CHURN_RATE_PERCENT
FROM CUSTOMERS;

-- 2. Churn Rate by Number of Products
SELECT 
  NUM_OF_PRODUCTS,
  COUNT(*) AS TOTAL,
  SUM(CASE WHEN EXITED = TRUE THEN 1 ELSE 0 END) AS CHURNED,
  ROUND(CHURNED * 100.0 / TOTAL, 2) AS CHURN_RATE
FROM CUSTOMERS
GROUP BY NUM_OF_PRODUCTS
ORDER BY NUM_OF_PRODUCTS;

-- 3. Churn Rate by Active / Inactive Customers
SELECT 
  IS_ACTIVE,
  COUNT(*) AS TOTAL,
  SUM(CASE WHEN EXITED = TRUE THEN 1 ELSE 0 END) AS CHURNED,
  ROUND(CHURNED * 100.0 / TOTAL, 2) AS CHURN_RATE
FROM CUSTOMERS
GROUP BY IS_ACTIVE;

-- 4. High Risk Customers - 1 Product + Inactive
SELECT 
  COUNT(*) AS HIGH_RISK_TOTAL,
  SUM(CASE WHEN EXITED = TRUE THEN 1 ELSE 0 END) AS CHURNED,
  ROUND(CHURNED * 100.0 / HIGH_RISK_TOTAL, 2) AS CHURN_RATE
FROM CUSTOMERS
WHERE NUM_OF_PRODUCTS = 1 AND IS_ACTIVE = FALSE;

-- 5. Churn by Age Group
SELECT 
  CASE 
    WHEN AGE < 30 THEN '18-29'
    WHEN AGE BETWEEN 30 AND 45 THEN '30-45'
    ELSE '45+'
  END AS AGE_GROUP,
  COUNT(*) AS TOTAL,
  SUM(CASE WHEN EXITED = TRUE THEN 1 ELSE 0 END) AS CHURNED
FROM CUSTOMERS
GROUP BY AGE_GROUP;